const PDFDocument = require('pdfkit');

exports.generatePDF = (report, profile, res) => {
  const doc = new PDFDocument({ margin: 50 });

  res.setHeader('Content-Type', 'application/pdf');
  res.setHeader('Content-Disposition', 'attachment; filename="health_report.pdf"');

  doc.pipe(res);

  // Header
  doc.fontSize(24).fillColor('#2c3e50').text('HealthGuard', { align: 'center' });
  doc.fontSize(14).fillColor('#7f8c8d').text('Smart Health Awareness & Disease Prevention Report', { align: 'center' });
  doc.moveDown(2);

  // Profile
  doc.fontSize(18).fillColor('#2c3e50').text('Patient Profile');
  doc.moveTo(50, doc.y).lineTo(550, doc.y).stroke();
  doc.moveDown(0.5);
  doc.fontSize(12).fillColor('#34495e');
  if (profile.name) doc.text(`Name: ${profile.name}`, { stroke: true });
  doc.text(`Age: ${profile.age} years | Gender: ${profile.gender}`);
  doc.text(`Height: ${profile.height} cm | Weight: ${profile.weight} kg`);
  doc.text(`BMI: ${profile.bmi} (${profile.bmiCategory})`);
  doc.moveDown(1);

  // Health Score
  doc.fontSize(18).fillColor('#2c3e50').text('Health Analysis');
  doc.moveTo(50, doc.y).lineTo(550, doc.y).stroke();
  doc.moveDown(0.5);
  
  doc.fontSize(14).fillColor(report.score > 70 ? '#27ae60' : '#e74c3c').text(`Overall Health Score: ${report.score}/100`);
  doc.moveDown(1);

  // Predictions
  if (report.predictedDiseases && report.predictedDiseases.length > 0) {
    doc.fontSize(16).fillColor('#2c3e50').text('Predicted Risks');
    report.predictedDiseases.forEach(p => {
      doc.fontSize(12).fillColor('#c0392b').text(`• ${p.disease} (Risk Level: ${p.riskLevel})`);
    });
    doc.moveDown(1);
  }

  // Recommendations
  if (report.recommendations) {
    doc.fontSize(18).fillColor('#2c3e50').text('Action Plan & Recommendations');
    doc.moveTo(50, doc.y).lineTo(550, doc.y).stroke();
    doc.moveDown(0.5);

    doc.fontSize(14).text('Nutrition');
    report.recommendations.nutrition.forEach(r => doc.fontSize(12).text(`• ${r}`));
    doc.moveDown(0.5);

    doc.fontSize(14).text('Exercise');
    report.recommendations.exercise.forEach(r => doc.fontSize(12).text(`• ${r}`));
    doc.moveDown(0.5);

    doc.fontSize(14).text('Prevention');
    report.recommendations.prevention.forEach(r => doc.fontSize(12).text(`• ${r}`));
    doc.moveDown(0.5);

    doc.fontSize(14).text('General Advice');
    report.recommendations.advice.forEach(r => doc.fontSize(12).text(`• ${r}`));
  }

  // Footer
  doc.moveDown(3);
  doc.fontSize(10).fillColor('#95a5a6').text('Disclaimer: This report is generated by a rule-based engine and is not a medical diagnosis. Consult a certified medical professional for accurate advice.', { align: 'center' });

  doc.end();
};
